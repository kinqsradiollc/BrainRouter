#!/usr/bin/env bash
# Clone brainrouter/.env into one self-contained env file per BrainRouter config,
# under envs/.env.benchmark_<config>. Each clone keeps the base infra (LLM +
# embedding endpoints/keys, JWT) but pins the recall pipeline knobs for that one
# config, so you can benchmark each pipeline mode individually.
#
# Files contain copied API keys → they are git-ignored. Re-run any time.
set -uo pipefail

BENCH=/Users/anhdang/Documents/Github/BrainRouter/brainrouter-benchmark
BASE=/Users/anhdang/Documents/Github/BrainRouter/brainrouter/.env
OUT="$BENCH/envs"

[ -f "$BASE" ] || { echo "ERROR: base env not found: $BASE"; exit 1; }
mkdir -p "$OUT"

# knobs we vary per config — stripped from the base clone, then re-set per config
STRIP='^(BRAINROUTER_LLM_MODEL|BRAINROUTER_RELEVANCE_JUDGE_MODEL|BRAINROUTER_RELEVANCE_JUDGE_ENABLED|BRAINROUTER_EMBEDDING_API_KEY|BRAINROUTER_RECALL_TOP_RESULTS|BRAINROUTER_RECALL_FTS_LIMIT|BRAINROUTER_RECALL_VEC_LIMIT|BRAINROUTER_RECALL_RERANK_POOL|BRAINROUTER_RECALL_DIVERSITY|BRAINROUTER_RECALL_DIVERSITY_LAMBDA|BRAINROUTER_RERANKER_API_KEY|BRAINROUTER_RERANKER_ENDPOINT|BRAINROUTER_RERANKER_MODEL|BRAINROUTER_RERANKER_TOP_N)='

# model is pinned for all benchmark configs (fast local judge/extractor)
COMMON=$'BRAINROUTER_LLM_MODEL=google/gemma-4-e2b\nBRAINROUTER_RELEVANCE_JUDGE_MODEL=google/gemma-4-e2b'

# Reranker endpoint for the reranker/full configs. NOTE: LM Studio does NOT
# expose /v1/rerank — point this at a Cohere- or vLLM-compatible rerank service,
# otherwise those configs fall back to RRF (bench-one.sh warns when that happens).
#   RERANKER_ENDPOINT=https://my-rerank/v1/rerank bash make-bench-envs.sh
RERANKER_ENDPOINT="${RERANKER_ENDPOINT:-http://localhost:1234/v1/rerank}"

emit() {
  local name="$1" desc="$2" body="$3"
  local f="$OUT/.env.benchmark_$name"
  {
    echo "# Auto-generated by make-bench-envs.sh"
    echo "# config: $name — $desc"
    echo "# clone of brainrouter/.env + pinned recall knobs. DO NOT COMMIT (copied API keys)."
    grep -vE "$STRIP" "$BASE"
    echo ""
    echo "# ---- benchmark knobs: $name ----"
    echo "$COMMON"
    printf '%s\n' "$body"
  } > "$f"
  echo "wrote $f"
}

# Embedding note: omitting BRAINROUTER_EMBEDDING_API_KEY lets the server fall
# back to the LLM key (embeddings ON). Setting it empty disables embeddings
# (keyword-only). Reranker is ON only when BRAINROUTER_RERANKER_API_KEY is set.

emit keyword "FTS / keyword only (vector OFF), no judge" "$(cat <<'EOF'
BRAINROUTER_EMBEDDING_API_KEY=
BRAINROUTER_RELEVANCE_JUDGE_ENABLED=false
BRAINROUTER_RECALL_TOP_RESULTS=20
BRAINROUTER_RECALL_FTS_LIMIT=20
BRAINROUTER_RECALL_VEC_LIMIT=20
BRAINROUTER_RECALL_DIVERSITY=off
EOF
)"

emit vector_rrf "FTS + vector, RRF fusion only (no MMR, no judge)" "$(cat <<'EOF'
BRAINROUTER_RELEVANCE_JUDGE_ENABLED=false
BRAINROUTER_RECALL_TOP_RESULTS=20
BRAINROUTER_RECALL_FTS_LIMIT=20
BRAINROUTER_RECALL_VEC_LIMIT=20
BRAINROUTER_RECALL_DIVERSITY=off
EOF
)"

emit vector_mmr "FTS + vector + MMR diversity (no judge)" "$(cat <<'EOF'
BRAINROUTER_RELEVANCE_JUDGE_ENABLED=false
BRAINROUTER_RECALL_TOP_RESULTS=20
BRAINROUTER_RECALL_FTS_LIMIT=20
BRAINROUTER_RECALL_VEC_LIMIT=20
BRAINROUTER_RECALL_DIVERSITY=on
EOF
)"

emit reranker "FTS + vector + cross-encoder reranker (needs a /v1/rerank service), no judge" "$(cat <<EOF
BRAINROUTER_RELEVANCE_JUDGE_ENABLED=false
BRAINROUTER_RECALL_TOP_RESULTS=20
BRAINROUTER_RECALL_FTS_LIMIT=20
BRAINROUTER_RECALL_VEC_LIMIT=20
BRAINROUTER_RECALL_RERANK_POOL=40
BRAINROUTER_RERANKER_ENDPOINT=$RERANKER_ENDPOINT
BRAINROUTER_RERANKER_API_KEY=local
BRAINROUTER_RERANKER_MODEL=bge-reranker-v2-m3
BRAINROUTER_RERANKER_TOP_N=20
EOF
)"

emit judge "FTS + vector + LLM relevance judge, return up to 20" "$(cat <<'EOF'
BRAINROUTER_RELEVANCE_JUDGE_ENABLED=true
BRAINROUTER_RECALL_TOP_RESULTS=20
BRAINROUTER_RECALL_FTS_LIMIT=20
BRAINROUTER_RECALL_VEC_LIMIT=20
BRAINROUTER_RECALL_DIVERSITY=off
EOF
)"

emit precision "Default precision-first: judge ON, top-5" "$(cat <<'EOF'
BRAINROUTER_RELEVANCE_JUDGE_ENABLED=true
BRAINROUTER_RECALL_TOP_RESULTS=5
BRAINROUTER_RECALL_DIVERSITY=off
EOF
)"

emit full "Everything ON: vector + reranker + judge + MMR, top-20" "$(cat <<EOF
BRAINROUTER_RELEVANCE_JUDGE_ENABLED=true
BRAINROUTER_RECALL_TOP_RESULTS=20
BRAINROUTER_RECALL_FTS_LIMIT=20
BRAINROUTER_RECALL_VEC_LIMIT=20
BRAINROUTER_RECALL_RERANK_POOL=40
BRAINROUTER_RECALL_DIVERSITY=on
BRAINROUTER_RERANKER_ENDPOINT=$RERANKER_ENDPOINT
BRAINROUTER_RERANKER_API_KEY=local
BRAINROUTER_RERANKER_MODEL=bge-reranker-v2-m3
BRAINROUTER_RERANKER_TOP_N=20
EOF
)"

echo ""
echo "Done. ${OUT}/.env.benchmark_*  (edit/add freely; one file = one config)"
